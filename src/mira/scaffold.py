"""Domain-agent scaffold generator (ADR-016) — the ``mira-scaffold`` console script.

``mira-scaffold new-domain <name> --tool-prefix <p>`` generates every artifact a
new domain specialist needs, with the platform invariants wired at creation:

* a connector skeleton with typed, **fail-closed** entitlement-bearing tool specs
  (ADR-020/031) — or, with ``--domain-kind mcp``, a specialist bound to the
  declared MCP server registry (``MCP_SERVERS`` env, ADR-020) instead of a local
  connector;
* a specialist module built on the shared subgraph scaffold (ADR-014) with a
  ``DomainSpec``, a representative-query placeholder, a ``query_inference`` hook
  stub, and the agent-card snippet + registration instructions in its docstring
  (ADR-035);
* minimal **passing** tests over the skeleton (protocol conformance, DomainSpec
  identity, empty-allowlist fail-closed);
* the ``specs/<name>-specialist/`` spec/plan/tasks trio; and
* an ``evals/goldens/<name>.jsonl.example`` golden stub for the ADR-045 gate
  (rename to ``.jsonl`` once the representative query answers end-to-end).

Generation is template-based (strings embedded in this module — no external
template files, no network) and **refuses to overwrite**: if any target path
exists, nothing is written and the command fails loudly.
"""

