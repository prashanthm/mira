def _render(template: str, **subs: str) -> str:
    return Template(template).substitute(**subs)


def _validate_name(name: str) -> str:
    if not _NAME_RE.fullmatch(name):
        raise ScaffoldError(
            f"domain name {name!r} must match [a-z][a-z0-9_]* (a Python module name)"
        )
    return name


def _normalize_prefix(tool_prefix: str) -> str:
    prefix = tool_prefix if tool_prefix.endswith(".") else f"{tool_prefix}."
    if not _PREFIX_RE.fullmatch(prefix):
        raise ScaffoldError(
            f"tool prefix {tool_prefix!r} must match [a-z][a-z0-9_.-]* "
            "(a trailing '.' is appended if missing)"
        )
    return prefix


def new_domain(
    name: str,
    tool_prefix: str,
    out: Path,
    *,
    domain_kind: str = "connector",
) -> list[Path]:
    """Generate every artifact for a new domain under ``out``; return the paths.

    Refuses to overwrite: if any target file already exists, raises
    :class:`ScaffoldError` and writes nothing.
    """
    name = _validate_name(name)
    prefix = _normalize_prefix(tool_prefix)
    if domain_kind not in ("connector", "mcp"):
        raise ScaffoldError(f"unknown --domain-kind {domain_kind!r} (connector|mcp)")

    source_type = prefix[:-1]
    subs = {
        "name": name,
        "prefix": prefix,
        "source_type": source_type,
        "upper": name.upper(),
        "title": name.replace("_", " ").title(),
        "class_name": "".join(part.title() for part in name.split("_")),
    }

    if domain_kind == "connector":
        specialist_docstring = _render(_SPECIALIST_DOCSTRING_CONNECTOR, **subs)
        source_note = (
            f"bind the `mira.connectors.{name}` connector skeleton to the real source"
        )
        plan_files = "\n".join(
            (
                f"| `src/mira/connectors/{name}.py` | Connector skeleton "
                f"(sample `lookup` capability, `{prefix}*` tool specs) |",
                f"| `src/mira/orchestration/specialists/{name}.py` | DomainSpec + "
                "specialist builder + inference hook stub |",
                f"| `tests/test_{name}_connector.py`, `tests/test_{name}_specialist.py` "
                "| Passing skeleton tests |",
            )
        )
        test_paths = f"tests/test_{name}_connector.py"
    else:
        specialist_docstring = _render(_SPECIALIST_DOCSTRING_MCP, **subs)
        source_note = (
            f"declare the MCP server in `MCP_SERVERS` and bind its `{prefix}*` tools"
        )
        plan_files = "\n".join(
            (
                f"| `src/mira/orchestration/specialists/{name}.py` | DomainSpec + "
                "specialist builder + inference hook stub (MCP-bound domain) |",
                f"| `tests/test_{name}_specialist.py` | Passing skeleton tests |",
            )
        )
        test_paths = f"tests/test_{name}_specialist.py"

    specialist_module = f'"""{specialist_docstring}"""' + _render(_SPECIALIST_BODY, **subs)

    doc_subs = {**subs, "source_note": source_note, "test_paths": test_paths}
    files: dict[Path, str] = {}
    if domain_kind == "connector":
        files[Path("src/mira/connectors") / f"{name}.py"] = _render(
            _CONNECTOR_TEMPLATE, **subs
        )
        files[Path("tests") / f"test_{name}_connector.py"] = _render(
            _CONNECTOR_TEST_TEMPLATE, **subs
        )
    files[Path("src/mira/orchestration/specialists") / f"{name}.py"] = specialist_module
    files[Path("tests") / f"test_{name}_specialist.py"] = _render(
        _SPECIALIST_TEST_TEMPLATE, **subs
    )
    spec_dir = Path("specs") / f"{name}-specialist"
    files[spec_dir / "spec.md"] = _render(_SPEC_TEMPLATE, **doc_subs)
    files[spec_dir / "plan.md"] = _render(_PLAN_TEMPLATE, **doc_subs, plan_files=plan_files)
    files[spec_dir / "tasks.md"] = _render(_TASKS_TEMPLATE, **doc_subs)
    files[Path("evals/goldens") / f"{name}.jsonl.example"] = _render(
        _GOLDEN_TEMPLATE, **subs
    )

    out = out.resolve()
    existing = [rel for rel in files if (out / rel).exists()]
    if existing:
        listing = ", ".join(str(rel) for rel in sorted(existing))
        raise ScaffoldError(
            f"refusing to overwrite existing files under {out}: {listing}"
        )

    written: list[Path] = []
    for rel, content in files.items():
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        written.append(target)
    return sorted(written)


def main(argv: list[str] | None = None) -> int:
    """Console entry point for ``mira-scaffold``."""
    parser = argparse.ArgumentParser(
        prog="mira-scaffold",
        description="Generate Mira domain-agent artifacts (ADR-016).",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)
    new = subparsers.add_parser(
        "new-domain", help="Generate connector/specialist/tests/spec/golden artifacts"
    )
    new.add_argument("name", help="domain id, e.g. 'inventory' ([a-z][a-z0-9_]*)")
    new.add_argument(
        "--tool-prefix",
        required=True,
        help="MCP tool-name prefix for the domain allow-list, e.g. 'inventory.'",
    )
    new.add_argument(
        "--out",
        type=Path,
        default=Path.cwd(),
        help="repository root to generate into (default: current directory)",
    )
    new.add_argument(
        "--domain-kind",
        choices=("connector", "mcp"),
        default="connector",
        help="'connector' generates a local connector skeleton; "
        "'mcp' binds the domain to the declared MCP server registry instead",
    )
    args = parser.parse_args(argv)

    try:
        written = new_domain(
            args.name, args.tool_prefix, args.out, domain_kind=args.domain_kind
        )
    except ScaffoldError as exc:
        print(f"mira-scaffold: error: {exc}", file=sys.stderr)
        return 1

    for path in written:
        print(f"generated {path}")
    print(
        f"next: wire the agent card (see the specialist module docstring), then "
        f"promote evals/goldens/{args.name}.jsonl.example (ADR-045)."
    )
    return 0


